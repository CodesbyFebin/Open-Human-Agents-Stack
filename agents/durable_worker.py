# agents/durable_worker.py
# Pydantic AI durable coding worker with sandbox isolation

import os
import asyncio
from typing import Literal
from pydantic import BaseModel, Field
from pydantic_ai import Agent, RunContext
from pydantic_ai.capabilities import WebSearch

class CodingTaskOutput(BaseModel):
    status: Literal['success', 'requires_review', 'failed']
    file_path_modified: str = Field(description="The source tree path targeted for updates.")
    diff_payload: str = Field(description="Unified git diff format changes.")
    verification_log: str = Field(description="Output log generated by execution tests.")

durable_coder = Agent(
    'anthropic:claude-3-7-sonnet',
    output_type=CodingTaskOutput,
    instructions="""
    You operate under strict production boundaries. 
    1. Always run execution scripts to reproduce issues prior to writing code.
    2. Enforce minimal structural modifications to protect adjacent operations.
    3. Verify outputs via testing pipelines before exporting task results.
    """
)

@durable_coder.tool
async def read_isolated_workspace(ctx: RunContext, target_file: str) -> str:
    """Safely extracts raw text content from the assigned runner workspace sandboxes."""
    base_sandbox = os.path.join("sandboxes", str(ctx.deps.pod_id), "workspace")
    safe_path = os.path.abspath(os.path.join(base_sandbox, target_file))
    
    if not safe_path.startswith(os.path.abspath(base_sandbox)):
        raise PermissionError("Access violation: requested path targets files outside sandboxed boundary.")
        
    if not os.path.exists(safe_path):
        return f"Error: target file {target_file} not found."
        
    with open(safe_path, 'r', encoding='utf-8') as f:
        return f.read()

async def execute_durable_loop(pod_id: str, prompt: str):
    """Executes a transaction-isolated worker run with telemetry tracking hooks."""
    class Dependencies:
        def __init__(self):
            self.pod_id = pod_id

    deps = Dependencies()
    result = await durable_coder.run(prompt, deps=deps)
    return result.output
